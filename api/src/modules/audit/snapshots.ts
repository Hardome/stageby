export function snapshot(entityType: string, row: Record<string, unknown>): Record<string, unknown> {
  const allowed = fields[entityType];
  if (!allowed) throw new Error(`Unsupported audit entity: ${entityType}`);
  return JSON.parse(
    JSON.stringify(Object.fromEntries(allowed.map((field) => [field, row[field]])), (_key, value: unknown) =>
      typeof value === 'bigint' ? value.toString() : value,
    ),
  ) as Record<string, unknown>;
}
